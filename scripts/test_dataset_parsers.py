class ShippedTableTests(unittest.TestCase):
    def parse(self, text):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "CalendarDataset.swift"
            path.write_text(text, encoding="utf-8")
            return dataset_table.shipped_table(path)

    def test_reads_only_the_indented_literal(self):
        # Two decoys precede the data block, and both must be inert. The
        # `public let years` declaration is row-shaped to the reader but not to
        # the row regex; the doc-comment year row is genuinely row-shaped, so a
        # bare `years: [` anchor would swallow it and the expected rows would
        # come back as 1970 too. Only a row-shaped decoy can prove the anchor.
        self.assertEqual(self.parse(DATASET_HEADER), SHIPPED_ROWS)

    def test_exits_when_no_years_block(self):
        text = "public struct CalendarDataset {\n    public let years: [Int: [Int]]\n}\n"
        with self.assertRaisesRegex(SystemExit, "format changed"):
            self.parse(text)

    def test_exits_when_years_block_has_no_rows(self):
        text = DATASET_HEADER.replace(
            """\
            1975: [31, 31, 32, 32, 31, 30, 30, 29, 30, 29, 30, 30],
            1976: [31, 32, 31, 32, 31, 30, 30, 30, 29, 29, 30, 31],
            1977: [30, 32, 31, 32, 31, 30, 30, 30, 29, 30, 29, 31],
""",
            "",
        )
        with self.assertRaisesRegex(SystemExit, "format changed"):
            self.parse(text)


class SourceParserTests(unittest.TestCase):
    def setUp(self):
        del vds.NOTES[:]

    def test_medic_keys_are_ints_and_impossible_years_are_noted(self):
        rows = vds.parse_medic(MEDIC_BODY)
        self.assertEqual(sorted(rows), [2000, 2081])
        self.assertEqual(rows[2000], [30, 32, 31, 32, 31, 30, 30, 30, 29, 30, 29, 31])
        self.assertEqual(sum(rows[2081]), 367)
        self.assertEqual(len(vds.NOTES), 1)
        self.assertIn("2081 BS sums to 367 days", vds.NOTES[0])

    def test_go_bs_takes_the_year_from_the_trailing_comment(self):
        self.assertEqual(
            vds.parse_go_bs(GO_BS_BODY),
            {
                1979: [31, 31, 32, 32, 31, 30, 30, 29, 30, 29, 30, 30],
                1980: [31, 32, 31, 32, 31, 30, 30, 30, 29, 29, 30, 31],
                1981: [31, 31, 31, 32, 31, 31, 29, 30, 30, 29, 30, 30],
            },
        )

    def test_go_bs_without_comments_yields_nothing(self):
        body = GO_BS_BODY.replace(", // 1979", "").replace(", // 1980", "").replace(", // 1981", "")
        self.assertEqual(vds.parse_go_bs(body), {})

    def test_nepali_date_follows_the_declared_month_order(self):
        rows = vds.parse_nepali_date(NEPALI_DATE_BODY)
        self.assertEqual(sorted(rows), [2000, 2001])
        self.assertEqual(rows[2000], [30, 32, 31, 32, 31, 30, 30, 30, 29, 30, 29, 31])
        self.assertEqual(rows[2001], [31, 31, 32, 31, 31, 31, 30, 29, 30, 29, 30, 30])

    def test_nepali_date_omits_a_year_missing_a_month(self):
        # Falgun and Chaitra dropped from 2001: a partial year would be compared
        # month-for-month against a shipped row as if it were a disagreement.
        body = NEPALI_DATE_BODY.replace("    Falgun: 30,\n    Chaitra: 30,\n", "")
        self.assertEqual(sorted(vds.parse_nepali_date(body)), [2000])

    def test_askbuddie_quoted_year_rows(self):
        self.assertEqual(
            vds.parse_askbuddie(ASKBUDDIE_BODY),
            {
                1975: [31, 31, 32, 32, 31, 30, 30, 29, 30, 29, 30, 30],
                1976: [31, 32, 31, 32, 31, 30, 30, 30, 29, 29, 30, 31],
            },
        )


